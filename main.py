"""
Selfbot для авто-прохождения данжей в Solo Rank — RPG Бот (Telethon, MTProto).

Логика (как описано пользователем):
1. /profile -> парсим "Мощь: N"
2. /dungeon -> парсим список данжей (номер, DEF) и кнопки "Войти #N" / "Сбросить список"
3. Выбираем данж с максимальным DEF <= Мощь
   - если такого нет и есть сбросы (X/5 > 0) -> "Сбросить список", повторить выбор
   - если такого нет и сбросов 0 -> берём самый слабый (мин. DEF) данж
4. Жмём "Войти #N"
   - если бот пишет "Недостаточно энергии" -> /energy
   - если "Низкое HP." -> /heal
   - если "Недостаточно энергии и низкое HP." -> /energy И /heal
     (кнопки подтверждения "Войти в истощении"/"Отмена" НЕ трогаем)
   - после этого заново /dungeon -> выбор -> "Войти #N" (повторяем, если предупреждение выскочит снова)
5. Если вход успешен ("Инстанс-данж запущен") -> ждём отчёт ("Отчёт инстанс-данжа", ~3 мин)
6. Возвращаемся к шагу 1, бесконечный цикл

ВАЖНО:
- Это автоматизация ТВОЕГО собственного игрового аккаунта в игровом Telegram-боте
  (не атака на чужие системы, не рассылка, не эксплойт). Тем не менее использование
  селфботов может нарушать правила самого игрового бота/чата — ответственность на тебе,
  учти риск бана в игре.
- Проверь несколько live-прогонов на паре итераций перед тем как оставлять бота
  надолго без присмотра — форматы сообщений у игровых ботов иногда меняются
  (сезонные ивенты, баланс), тогда парсер надо будет подправить.
"""

import asyncio

from telethon import TelegramClient

from config import API_ID, API_HASH, SESSION_NAME, log
from dungeon_cycle import run_cycle


async def main():
    client = TelegramClient(SESSION_NAME, API_ID, API_HASH)
    await client.start()
    log.info("Клиент запущен, начинаю бесконечный цикл данжей.")

    while True:
        try:
            await run_cycle(client)
        except asyncio.TimeoutError as e:
            log.error(f"Таймаут ожидания ответа бота: {e}. Пауза 30с и повтор.")
            await asyncio.sleep(30)
        except Exception as e:
            log.exception(f"Неожиданная ошибка: {e}. Пауза 30с и повтор.")
            await asyncio.sleep(30)


if __name__ == "__main__":
    asyncio.run(main())